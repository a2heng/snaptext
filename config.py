# ============================================================================
# 一、存储位置
# ============================================================================
# 截图和 OCR 结果默认存到家目录下的 ~/.snaptext 里：
#
#   图片目录：DATA_DIR/img/    例如 ~/.snaptext/img/20260812_132607_733.png
#   文本目录：DATA_DIR/text/   例如 ~/.snaptext/text/20260812_132607_733.txt
#
# DATA_DIR：
#   - 默认 "~/.snaptext"（即 /home/你的用户名/.snaptext）。
#   - 想换地方存，改成别的路径即可，程序会自动创建。
#   - 注意：换数据目录**不会**影响"单实例锁"，锁是另一个文件，见 LOCK_PATH。
#
# LOCK_PATH：
#   - 默认 "~/.snaptext.lock"，用来防止同时开两个程序实例（多开会抢热键）。
#   - 它故意放在数据目录**外面**：这样即使你清空/删除 ~/.snaptext，
#     锁也还在，不会误以为"没有程序在跑"。
#   - 一般不用改。如果改了，请也放在数据目录外面，并确保目录可写。
#
# 示例：把截图改存到 /home/me/Screenshots：
#   DATA_DIR = "/home/me/Screenshots"
#
# DATA_DIR   = "~/.snaptext"
# LOCK_PATH  = "~/.snaptext.lock"


# ============================================================================
# 二、全局热键
# ============================================================================
# 程序有两个快捷键，分工不同：
#
#   HOTKEY_IMAGE  截屏 → 保存选区图片 → 把图片复制到剪贴板
#   HOTKEY_OCR    截屏 → 保存图片 → OCR 识别文字 → 保存文本 → 把文字复制到剪贴板
#
# 【写法】格式是：修饰键 + 修饰键 + 键名，用英文加号连接，顺序无所谓。
#   修饰键（可写多个）：
#     shift      Ctrl 左边的 Shift 键
#     ctrl       Ctrl 键
#     alt        Alt 键
#     super      Super 键，就是键盘上的 Windows / Command 键
#   键名 = X11 键位名（keysym），常用：
#     x / c / v 等字母（字母不区分大小写，展示时自动转大写）
#     0-9 数字、F1-F12 功能键、Return、Space、Escape、Tab
#
# 一些写法示例：
#   "alt+x"             Alt+X
#   "ctrl+shift+e"      Ctrl+Shift+E
#   "super+1"           Windows 键 + 1
#   "F9"                只有 F9，不带任何修饰键
#
# 【注意】
#   1. CapsLock / NumLock 开关状态自动兼容，不用你处理。
#   2. 别改成和系统里其它软件冲突的快捷键，否则可能抢不赢或按了没反应。
#   3. ESC_KEY 是"选区时按它放弃这次截图"的兜底键，一般别动。
#   4. 托盘图标左键提示、右键菜单里显示的快捷键文字会自动跟随这里的改动。
#
# 示例：截图改成 Alt+Z、OCR 改成 Alt+V：
#   HOTKEY_IMAGE = "alt+z"
#   HOTKEY_OCR   = "alt+v"
#
# HOTKEY_IMAGE = "alt+x"
# HOTKEY_OCR   = "alt+c"
# ESC_KEY      = "Escape"


# ============================================================================
# 三、OCR 引擎参数
# ============================================================================
# 说明：下面三个参数不是随便填的。它们是从"旧版本有 bug / 慢"的状态调到现在的
# 结果，改回旧值会复现那些问题。想调识别效果，只动 OCR_DET_LIMIT_SIDE_LEN 即可，
# 另外两个保持默认。完整来龙去脉见 AGENTS.md「OCR 踩过的坑」。
#
# ---------------------------------------------------------------
# OCR_DET_LIMIT_SIDE_LEN   （最常用，推荐只改这个）
# ---------------------------------------------------------------
#   - 含义：识别前把图片缩放到的"长边上限"，单位像素。
#   - 作用：数字越大，识别越清晰（小字看得清），但速度越慢、占内存越多；
#           数字越小，识别越快，但字太小会认错。
#   - 默认 960：正常屏幕速度和清晰度都够用。
#   - 建议：4K 高分屏上想更准可以试 1280 或 1600（会明显变慢，请自行取舍）；
#           觉得太慢就调回 960。别低于 64（程序会拒绝）。
#
# 示例：4K 屏想更清晰：
#   OCR_DET_LIMIT_SIDE_LEN = 1280
#
# ---------------------------------------------------------------
# OCR_DET_LIMIT_TYPE       （一般别动）
# ---------------------------------------------------------------
#   - 取值只有两个："max" 或 "min"。
#   - "max"（默认）：缩放时长边封顶，宽扁图不会无脑放大，识别快。
#   - "min"：缩放时短边拉到固定长度，宽扁图会被放大成巨图，能慢到 3-4 秒。
#     这就是旧版本慢的根因，别改回去。
#
# ---------------------------------------------------------------
# OCR_WIDTH_HEIGHT_RATIO   （一般别动）
# ---------------------------------------------------------------
#   - 含义：图片"宽高比"超过这个数时，识别引擎会跳过检测直接整图喂给识别，
#     导致极窄长条（比如一列竖排文字）识别为空。
#   - 默认 100，几乎什么图都会正常走检测。改回 8 会复现"窄条识别不出字"的 bug。
#
# OCR_WIDTH_HEIGHT_RATIO = 100
# OCR_DET_LIMIT_TYPE     = "max"
# OCR_DET_LIMIT_SIDE_LEN = 960


# ============================================================================
# 四、选区样式（拉框时的外观）
# ============================================================================
# 这三个只影响"拉框选区域"时看到的样子，不影响识别结果。
#
# SELECT_MIN_SIZE：
#   - 最小选区边长（逻辑像素）。拖出来的框如果宽或高小于它，会被当成"误操作"，
#     直接取消这次截图。
#   - 默认 5（现状）。改大一点（比如 10）可以防止不小心点到一下就截图。
#
# SELECT_MASK_ALPHA：
#   - 拉框时，没选中区域的"遮罩黑度"，取值 0-255。
#   - 0 = 完全透明（没选中区域完全看得见），255 = 全黑（几乎看不到屏幕）。
#   - 默认 100（现状）。觉得太黑看不清底下内容，就调小。
#
# SELECT_BORDER_COLOR：
#   - 选区蓝色边框的颜色，格式 #RRGGBB（红绿蓝各两位十六进制）。
#   - 默认 "#0078D7"（Windows 蓝，现状）。想换成红色就写 "#e53935"。
#
# 示例：遮罩淡一点、框改成红色、最小选区 10 像素：
#   SELECT_MIN_SIZE   = 10
#   SELECT_MASK_ALPHA = 60
#   SELECT_BORDER_COLOR = "#e53935"
#
# SELECT_MIN_SIZE      = 5
# SELECT_MASK_ALPHA    = 100
# SELECT_BORDER_COLOR  = "#0078D7"


# ============================================================================
# 五、行为 / 落盘
# ============================================================================
# 这几个控制"截图之后到底存不存盘、气泡提示停多久"。
#
# ---------------------------------------------------------------
# SAVE_IMAGES
# ---------------------------------------------------------------
#   - True（默认，现状）：截图图片存进 DATA_DIR/img/，OCR 出来的文本存进
#     DATA_DIR/text/。这样以后想翻历史截图/文字都在。
#   - False：图片和文本都**不写文件**，结果只进剪贴板（图片进剪贴板、
#     OCR 文字进剪贴板）。适合"不想在硬盘留屏幕截图"的场景。
#   - 关闭后 OCR 仍然正常工作（识别走内存，不依赖临时文件）。
#
# ---------------------------------------------------------------
# PREWARM_OCR
# ---------------------------------------------------------------
#   - True（默认，现状）：启动程序时在后台提前加载 onnx 模型，这样你第一次按
#     快捷键 OCR 时不用等那 0.8 秒。
#   - False：不预热，启动更省一点内存/CPU，但第一次按 OCR 要多等约 0.8 秒。
#
# ---------------------------------------------------------------
# NOTIFY_MS
# ---------------------------------------------------------------
#   - 托盘气泡提示停留的毫秒数（1 秒 = 1000 毫秒）。
#   - 默认 2000（2 秒，现状）。想看得久一点就调大，比如 5000。
#
# 示例：结果不落盘、气泡提示 5 秒：
#   SAVE_IMAGES = False
#   NOTIFY_MS   = 5000
#
# SAVE_IMAGES = True
# PREWARM_OCR = True
# NOTIFY_MS   = 2000


